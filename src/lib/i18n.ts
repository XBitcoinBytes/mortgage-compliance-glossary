export function hrefFor(lang: Lang, path: string): string {
  const clean = path.startsWith("/") ? path : `/${path}`;
  if (lang === "en") return clean === "" ? "/" : clean;
  if (clean === "/") return "/es";
  return `/es${clean}`;
}

export function switchLangHref(current: Lang, pathname: string): string {
  const other: Lang = current === "en" ? "es" : "en";
  let bare = pathname;
  if (bare.startsWith("/es/")) bare = bare.slice(3);
  else if (bare === "/es") bare = "/";
  return hrefFor(other, bare);
}
